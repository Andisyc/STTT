class SyntheticEnv:
    def __init__(self, override):
        self.num_envs, self.tick, self.closed = 1, 0, False
        self.action_space = SimpleNamespace(shape=(29,), low=-np.ones(29), high=np.ones(29))
        self.default_angles = np.zeros((1, 29))
        self.cfg = SimpleNamespace(
            ctrl_dt=override['ctrl_dt'], gait_clock_mode=override['gait_clock_mode'],
            gait_phase_enabled=override['gait_phase_enabled'], reward_config=SimpleNamespace(**override['reward_config']),
            control_config=SimpleNamespace(action_scale=0.5),
        )
        self.state = SimpleNamespace(
            terminated=np.zeros(1, dtype=bool), truncated=np.zeros(1, dtype=bool),
            info={'commands': np.array([[0.4, 0., 0.]], np.float32), 'gait_phase': np.zeros((1, 2)), 'current_actions': np.zeros((1, 29))},
        )
    def get_actuated_joint_names(self): return tuple(f'j{i}' for i in reversed(range(29)))
    def get_actuator_gains(self): return np.full(29, 50.), np.full(29, 2.)
    def get_sim_time_ns(self): return self.tick * 20_000_000
    def get_base_pos(self): return np.array([[self.tick * 0.01, self.tick * 0.003, 0.8]])
    def get_base_quat(self):
        yaw = self.tick * 0.01
        return np.array([[math.cos(yaw / 2), 0., 0., math.sin(yaw / 2)]])
    def get_base_ang_vel(self): return np.array([[0., 0., 0.5]])
    def get_dof_pos(self): return np.linspace(0.1, 0.3, 29)[None] + self.tick * 0.001
    def get_dof_vel(self): return np.zeros((1, 29))
    def set_autoreset(self, enabled): self.autoreset = enabled
    def close(self): self.closed = True


class SyntheticWrapper:
    def __init__(self, env, **_):
        self.env, self.actions = env, []
        self.terminal_next = False
    def reset(self):
        self.env.tick = 0
        self.env.state.terminated[:] = False
        return {'actor': torch.zeros(1, 98)}, {}
    def step(self, action):
        self.actions.append(action.detach().clone())
        self.env.state.info['current_actions'][:] = action.detach().numpy() * 0.7
        self.env.tick += 1
        self.env.state.info['gait_phase'] += 0.1
        terminal, self.terminal_next = self.terminal_next, False
        self.env.state.terminated[:] = terminal
        if terminal and getattr(self.env, 'autoreset', False):
            self.env.tick = 0
        return {'actor': torch.zeros(1, 98)}, torch.zeros(1), torch.tensor([terminal]), {}
    def close(self): self.env.close()


class DelayedPoses:
    """Transport delay only; measurements/alignment are generated by the actual pose runtime."""
    def __init__(self, env, config, *, delay=0):
        self.base = create_pose_runtime(env, config)
        self.delay, self.queue, self.closed = delay, [], False
        self.lost = False
        self.drop_initial = False
    @property
    def clock(self): return self.base.clock
    def begin_step(self): return self.base.begin_step()
    def complete_step(self, control):
        update = self.base.complete_step(control)
        self.queue.append(update.aligned)
        arrived = self.queue.pop(0) if len(self.queue) > self.delay else ()
        if self.drop_initial:
            arrived = tuple(item for item in arrived if item.control.transition_id != 0)
        return replace(update, aligned=arrived, status='lost' if self.lost else update.status, invalidated=self.lost)
    def reset(self):
        self.base.reset()
        self.queue.clear()
    def close(self):
        self.closed = True
        self.base.close()


def runtime_case(directory, *, online=False, delay=0, enabled=True):
    directory = Path(directory)
    directory.mkdir(parents=True)
    with torch.random.fork_rng():
        torch.manual_seed(9)
        policy = build_official_fada_student({
            'history_len': 4, 'pred_horizon': 3, 'planner_d_model': 8, 'planner_nhead': 2,
            'planner_num_layers': 1, 'planner_dim_feedforward': 16, 'planner_dropout': 0.,
            'idm_d_model': 8, 'idm_nhead': 2, 'idm_encoder_num_layers': 1, 'idm_decoder_num_layers': 1,
            'idm_dim_feedforward': 16, 'idm_dropout': 0., 'planner_use_action_history': True,
            'planner_predict_delta': True, 'idm_use_current_command_for_history': True,
        }).eval()
    terms = ('base_ang_vel', 'dof_pos', 'dof_vel', 'projected_gravity')
    preprocessing = {'term_order': list(terms), 'noise_enabled': False,
                     'term_scale': dict(zip(terms, (0.25, 2.5, 0.15, 1.))), 'term_noise': dict.fromkeys(terms, 0.)}
    object.__setattr__(policy, 'official_preprocessing', preprocessing)
    profile = OfficialFADAPlaybackProfile(
        source_identity={'run': 'synthetic_runtime_not_physics'}, joint_names=tuple(f'j{i}' for i in range(29)),
        default_joint_pos=(0.2,) * 29, action_scale=(0.35,) * 29, stiffness=(50.,) * 29,
        damping=(2.,) * 29, clip_actions=0.35, ctrl_dt=0.02, gait_frequency=1.5,
        gait_clock_mode='source_clock', phase_init=(0., math.pi),
    )
    checkpoint = directory / 'policy.pt'
    checkpoint.write_bytes(b'explicit synthetic policy loader seam, not a trained artifact')
    profile_path = directory / 'profile.yaml'
    OmegaConf.save(OmegaConf.create(asdict(profile)), profile_path)
    contract = response_contract_from_metadata({'contract': {
        'window_steps': 2, 'ctrl_dt': 0.02, 'history_length': 4, 'prediction_horizon': 3,
        'joint_names': list(profile.joint_names), 'position_scale': 2.5, 'velocity_scale': 0.15, 'tensor_dtype': 'float32',
    }, 'source': {'preprocessing': preprocessing, 'source_profile': asdict(profile),
                 'checkpoint_sha256': hashlib.sha256(checkpoint.read_bytes()).hexdigest(),
                 'delta_frame': 'window_start_horizontal_heading', 'delta_units': ['m', 'm', 'rad']}})
    with torch.random.fork_rng():
        torch.manual_seed(11)
        response = ResponseModel(4, 3, [16, 8])
    context = torch.linspace(-0.1, 0.1, 4 * response.context_dim).reshape(4, -1)
    context[:, 372:376] = 1.
    residual = torch.linspace(-0.02, 0.02, 4 * 29).reshape(4, 29)
    response.fit_normalization([(context, residual, torch.zeros(4, 3))], epsilon=1e-6)
    b_path = save_response_checkpoint(directory / 'b.pt', response, contract=contract, training_config={}, data_sources=[], metrics={'fixture': 'analytical'})
    node = OmegaConf.load(ROOT / 'conf/distill/path_following/online.yaml')
    node.checkpoint_path = str(b_path)
    node.pose.odometry_source = 'simulation'
    node.update_interval_steps = 2
    node.learning = {'actor': {'hidden_dims': [16, 8]}}
    cfg = OmegaConf.create({
        'training': {'task_name': 'G1WalkFlat', 'sim_backend': 'mujoco'},
        'official_playback': {'profile_path': str(profile_path)},
        'online_adaptation': {'enabled': online, 'window_size': 2, 'warmup_steps': 6, 'update_interval': 2, 'lora_rank': 2},
        'env': {'commands': {'resampling_time': 0., 'heading_command': False}},
    })
    if enabled:
        cfg.path_following = node
    environments, wrappers, sources = [], [], []
    def create_env(*_, env_cfg_override, **__):
        env = SyntheticEnv(env_cfg_override)
        environments.append(env)
        return env
    def create_wrapper(env, **kwargs):
        wrapper = SyntheticWrapper(env, **kwargs)
        wrappers.append(wrapper)
        return wrapper
    def create_poses(env, pose_config):
        poses = DelayedPoses(env, pose_config, delay=delay)
        sources.append(poses)
        return poses
    deps = {
        'resolve_checkpoint': lambda *_: checkpoint,
        'load_fada_policy': lambda *_, **__: LoadedOfficialFADAStudentPolicy(policy, {'source_identity': profile.source_identity, 'completed_steps': 1}),
        'create_env': create_env, 'wrapper_cls': create_wrapper, 'build_env_cfg_override': lambda _: {},
        'create_pose_runtime': create_poses,
    }
    playback = RslRlPlaybackConfig(task='G1WalkFlat', load_run='-1', checkpoint=None, action_mode='policy', policy_obs_mode='actor', algo_log_name='distill', log_root=None, num_envs=1)
    return SimpleNamespace(cfg=cfg, playback=playback, deps=deps, policy=policy, environments=environments, wrappers=wrappers, sources=sources)


def create_session(case) -> Any:
    session, _, _ = create_fada_playback_session(playback_cfg=case.playback, cfg=case.cfg, root_dir=ROOT, device='cpu', deps=case.deps, log=lambda _: None)
    session.reset()
    return session


@pytest.mark.parametrize('online', [False, True])
def test_zero_start_and_window_activation_preserve_actual_tracker_target(tmp_path, online):
    case = runtime_case(tmp_path / 'spatial', online=online)
    plain = runtime_case(tmp_path / 'plain', online=online, enabled=False)
    session, baseline = create_session(case), create_session(plain)
    planner, tracker = [], []
    handles = [
        case.policy.planner.register_forward_hook(lambda _, args, output: planner.append((output + args[0][:, -1:]).detach().clone())),
        case.policy.idm.register_forward_pre_hook(lambda _, args: tracker.append(args[3].detach().clone()) if not torch.is_grad_enabled() else None),
    ]
    windows = []
    runtime = session.controller
    original = runtime.updater.update
    def capture_windows(completed_windows, actor_context=None):
        windows.extend(completed_windows)
        return original(completed_windows, actor_context)
    runtime.updater.update = capture_windows
    try:
        for step in range(8):
            session.step_once()
            if step < 4:
                baseline.step_once()
                torch.testing.assert_close(session.actions, baseline.actions, atol=0, rtol=0)
        rows = list(runtime.trace)
        assert all(row['locked_rad'] == [0.] * 29 for row in rows[:4])
        assert any(value != 0 for value in rows[4]['locked_rad'])
        assert rows[4]['locked_rad'] == rows[5]['locked_rad']
        assert rows[6]['locked_rad'] == rows[7]['locked_rad']
        assert len(planner) == len(tracker) == 8
        for step in range(8):
            residual = torch.tensor(rows[step]['locked_rad']).reshape(1, 29)
            from unilab.algos.torch.sttt.path_following.intervention import compose_joint_position_residual
            expected = compose_joint_position_residual(planner[step], residual, ctrl_dt=0.02, position_scale=2.5, velocity_scale=0.15)
            torch.testing.assert_close(tracker[step], expected, atol=0, rtol=0)
        np.testing.assert_allclose(windows[0].controls[0].action, case.wrappers[0].actions[0][0].numpy() * 0.7, atol=1e-7)
        assert [window.window_id for window in windows] == [0, 1, 2, 3]
        assert runtime.updater.response_updates == 4 and runtime.updater.actor_updates == 3
        if online:
            assert session.last_update_stats['loss'] >= 0
        before = runtime.updater.actor.output.weight.detach().clone()
        session.reset()
        session.step_once()
        assert runtime.collector.reference.sequence_id == 2
        torch.testing.assert_close(runtime.updater.actor.output.weight, before, atol=0, rtol=0)
    finally:
        for handle in handles:
            handle.remove()
        session.close()
        baseline.close()
    assert case.environments[0].closed and case.sources[0].closed


def test_delayed_poses_keep_query_time_and_fixed_reference(tmp_path):
    case = runtime_case(tmp_path / 'delayed', delay=2)
    session = create_session(case)
    try:
        for _ in range(8):
            session.step_once()
        runtime = session.controller
        rows = list(runtime.trace)
        assert rows[0]['measurement_timestamp_ns'] is None
        assert rows[2]['measurement_timestamp_ns'] == 0
        assert rows[2]['observation_age_ns'] == 60_000_000
        assert runtime.collector.reference.timestamp_ns == 0
        assert runtime.updater.response_updates == 3
        assert runtime.updater.actor_updates == 2
        assert all(row['locked_rad'] == [0.] * 29 for row in rows[:6])
        assert rows[6]['locked_rad'] == rows[7]['locked_rad']
        assert rows[6]['errors_m_rad'][0] > 0
    finally:
        session.close()


@pytest.mark.parametrize('failure', ['lost', 'initial_missing', 'stale', 'clock_reset'])
def test_invalid_localization_halts_without_reanchoring(tmp_path, failure):
    case = runtime_case(tmp_path / failure, delay=20 if failure == 'stale' else 0)
    session = create_session(case)
    try:
        if failure == 'lost':
            case.sources[0].lost = True
        if failure == 'initial_missing':
            case.sources[0].drop_initial = True
        if failure == 'clock_reset':
            session.step_once()
            case.environments[0].tick = 0
        with pytest.raises((RuntimeError, ValueError)):
            for _ in range(14):
                session.step_once()
        assert session.controller.trace[-1]['event'] == 'halt'
        with pytest.raises(RuntimeError, match='stopped'):
            session.step_once()
    finally:
        session.close()
    assert case.sources[0].closed and case.environments[0].closed


def test_terminal_discards_window_before_physical_autoreset_clock_can_mix(tmp_path):
    case = runtime_case(tmp_path / 'terminal')
    session = create_session(case)
    try:
        session.set_autoreset(True)
        session.step_once()
        case.wrappers[0].terminal_next = True
        session.step_once()
        assert session.controller.updater.response_updates == 0
        session.step_once()
        assert session.controller.collector.reference.sequence_id == 2
        assert session.controller.collector.completed_windows == 0
    finally:
        session.close()


def test_incompatible_artifact_and_multiple_transforms_fail_before_env_allocation(tmp_path):
    case = runtime_case(tmp_path / 'bad')
    case.deps['resolve_checkpoint'](None).write_bytes(b'changed actual policy identity')
    with pytest.raises(ValueError, match='incompatible'):
        create_session(case)
    assert not case.environments
    with pytest.raises(ValueError, match='sole|owns'):
        create_fada_playback_session(playback_cfg=case.playback, cfg=case.cfg, root_dir=ROOT, device='cpu', deps=case.deps, future_transform=lambda q: q.planner_future)
    assert not case.environments
